'use strict';
const assert = require('node:assert/strict');
const { it } = require('node:test');
const request = require('supertest');
const { createApplication } = require('../src/app');

it('requires admin group approval and invitation approval, keeps multiple labels separate from permissions', async () => {
  const app = createApplication({ dbPath: ':memory:', envName: 'test', bcryptRounds: 4, disableOutboundNotifications: true });
  try {
    const admin = request.agent(app.app), faculty = request.agent(app.app), student = request.agent(app.app), outsider = request.agent(app.app), otherFaculty = request.agent(app.app);
    for (const [agent, email, password] of [[admin,'admin@demo.edu','Admin123!'],[faculty,'faculty@demo.edu','Faculty123!'],[student,'asha@demo.edu','Student123!'],[outsider,'ravi@demo.edu','Student123!'],[otherFaculty,'arjun@demo.edu','Faculty123!']]) await agent.post('/api/auth/login').send({ email,password }).expect(200);
    const f = (await faculty.get('/api/auth/me')).body.user, s = (await student.get('/api/auth/me')).body.user;
    const profile = { name: 'Asha Rao', department:'IT',section:'A',register_number:'S01',program:'BTech',academic_year:'2026-27',bio:'' };
    await student.put('/api/platform/profile').send(profile).expect(200);
    await admin.put(`/api/community/staff/${f.id}/designations`).send({designations:['HOD','Assistant Professor'],department:'IT',employeeId:'F01'}).expect(200);
    await faculty.put(`/api/community/staff/${f.id}/designations`).send({designations:['PT']}).expect(403);
    assert.deepEqual((await faculty.get('/api/platform/profile')).body.profile.designations,['ASSISTANT PROFESSOR','HOD']);
    await faculty.get('/api/community/staff').expect(403);
    const before = app.db.prepare('SELECT count(*) n FROM groups').get().n;
    const draft = { name:'IT student community',year:1,department:'IT',section:'A',joinable:false,autoAddMatches:false,facultyIds:[f.id] };
    const proposal = await faculty.post('/api/groups').send(draft).expect(201);
    assert.equal(proposal.body.status,'pending'); assert.equal(app.db.prepare('SELECT count(*) n FROM groups').get().n,before);
    await student.post('/api/groups').send(draft).expect(403);
    await faculty.post(`/api/community/requests/${proposal.body.requestId}/review`).send({decision:'approve'}).expect(403);
    const approved = await admin.post(`/api/community/requests/${proposal.body.requestId}/review`).send({decision:'approve'}).expect(200);
    const groupId = approved.body.group.id;
    await admin.post(`/api/community/requests/${proposal.body.requestId}/review`).send({decision:'approve'}).expect(409);
    await otherFaculty.post(`/api/community/groups/${groupId}/invitations`).send({}).expect(403);
    await student.post(`/api/community/groups/${groupId}/invitations`).send({}).expect(403);
    const invite = (await faculty.post(`/api/community/groups/${groupId}/invitations`).send({}).expect(201)).body;
    assert(!app.db.prepare('SELECT token_hash FROM group_invitations WHERE id=?').get(invite.id).token_hash.includes(invite.token));
    await outsider.get(`/api/community/invite/${invite.token}`).expect(403);
    await student.post(`/api/community/invite/${invite.token}`).expect(200);
    await student.post(`/api/community/invite/${invite.token}`).expect(200);
    assert.equal(app.db.prepare('SELECT count(*) n FROM group_join_requests WHERE group_id=?').get(groupId).n,1);
    assert(!app.db.prepare('SELECT 1 FROM student_group_memberships WHERE group_id=? AND student_id=?').get(groupId,s.id));
    const pending = (await faculty.get(`/api/community/groups/${groupId}`).expect(200)).body.requests[0];
    await student.post(`/api/community/join-requests/${pending.id}/review`).send({decision:'approve'}).expect(403);
    await otherFaculty.post(`/api/community/join-requests/${pending.id}/review`).send({decision:'approve'}).expect(403);
    await faculty.post(`/api/community/join-requests/${pending.id}/review`).send({decision:'approve'}).expect(200);
    assert(app.db.prepare('SELECT 1 FROM student_group_memberships WHERE group_id=? AND student_id=?').get(groupId,s.id));
    await faculty.post(`/api/community/join-requests/${pending.id}/review`).send({decision:'approve'}).expect(409);
    await faculty.post(`/api/community/invitations/${invite.id}/revoke`).expect(200);
    await student.get(`/api/community/invite/${invite.token}`).expect(404);
    const expired=(await faculty.post(`/api/community/groups/${groupId}/invitations`).send({days:1}).expect(201)).body;
    app.db.prepare("UPDATE group_invitations SET expires_at='2000-01-01' WHERE id=?").run(expired.id);
    await student.post(`/api/community/invite/${expired.token}`).expect(404);
    const sports={name:'Football team',kind:'activity',category:'sports',sportsType:'Outdoor',sportsName:'Football',facultyIds:[f.id]};
    await admin.post('/api/admin/groups').send(sports).expect(400);
    await admin.put(`/api/community/staff/${f.id}/designations`).send({designations:['HOD','Assistant Professor','PT']}).expect(200);
    const sportsGroup=(await admin.post('/api/admin/groups').send(sports).expect(201)).body.group;
    assert.equal(sportsGroup.category,'sports');
    await student.post('/api/memberships').send({groupId:sportsGroup.id,joined:true}).expect(200);
    assert(!app.db.prepare('SELECT 1 FROM student_group_memberships WHERE group_id=? AND student_id=?').get(sportsGroup.id,s.id));
    const otherId=(await otherFaculty.get('/api/auth/me')).body.user.id;
    await admin.post('/api/admin/groups').send({name:'Inherited department denied',parentGroupId:groupId,facultyIds:[otherId]}).expect(400);
    await admin.post('/api/admin/groups').send({name:'Inherited IT community',parentGroupId:groupId,facultyIds:[f.id]}).expect(201);
    const club=(await admin.post('/api/admin/groups').send({name:'Student innovation club',category:'club',studentManagerId:s.id,facultyIds:[f.id]}).expect(201)).body.group;
    await student.get(`/api/community/groups/${club.id}`).expect(403);
    await student.post(`/api/community/groups/${club.id}/invitations`).send({}).expect(403);
    await admin.put(`/api/community/staff/${f.id}/designations`).send({designations:['HOD','Assistant Professor']}).expect(200);
    await faculty.post(`/api/community/groups/${sportsGroup.id}/invitations`).send({}).expect(403);
    const rejected=(await faculty.post('/api/community/requests').send({name:'Rejected committee',category:'exam'}).expect(201)).body.requestId;
    await admin.post(`/api/community/requests/${rejected}/review`).send({decision:'reject',note:'Use the existing exam cell.'}).expect(200);
    assert(!app.db.prepare("SELECT 1 FROM groups WHERE name='Rejected committee'").get());
    assert.equal(app.db.pragma('foreign_key_check').length,0);
  } finally {app.close();}
});
