import { test, expect } from '@playwright/test';

test('approves a faculty group, assigns multiple labels, and joins through an approved QR invitation', async ({ page }, testInfo) => {
  const login = async (email,password) => { await page.request.post('/api/auth/logout'); expect((await page.request.post('/api/auth/login',{data:{email,password}})).ok()).toBeTruthy(); };
  await login('asha@demo.edu','Student123!');
  await page.request.put('/api/platform/profile',{data:{name:'Asha Rao',department:'IT',section:'A',register_number:'IT001',program:'BTech',academic_year:'2026-27',bio:''}});
  await login('admin@demo.edu','Admin123!');
  await page.goto('/admin/groups');
  const staff = page.locator('form').filter({has:page.getByRole('heading',{name:'Dr. Meera Shah',exact:true})});
  await staff.getByLabel('Staff department',{exact:true}).fill('IT');
  await staff.getByLabel('Staff ID',{exact:true}).fill('F001');
  await staff.getByLabel('Designations (comma separated)',{exact:true}).fill('HOD, Assistant Professor, PT');
  await staff.getByRole('button',{name:'Save staff designations'}).click();
  await expect(staff.getByRole('status')).toContainText('Staff designations saved.');
  await login('faculty@demo.edu','Faculty123!');
  await page.goto('/faculty/groups');
  await page.getByRole('button',{name:'Request group',exact:true}).click();
  const dialog = page.getByRole('dialog');
  const name = `IT Club ${testInfo.project.name} ${Date.now()}`;
  await dialog.getByLabel('Group name',{exact:true}).fill(name);
  await dialog.getByRole('combobox',{name:'Category',exact:true}).selectOption('club');
  await dialog.getByLabel('Department',{exact:true}).fill('IT');
  await dialog.getByLabel(/Add students matching these filters/).uncheck();
  await dialog.getByRole('combobox',{name:'Student club manager',exact:true}).selectOption({label:'Asha Rao'});
  await dialog.getByRole('button',{name:'Submit group request',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('article').filter({hasText:name})).toContainText('pending');
  await login('admin@demo.edu','Admin123!');
  await page.goto('/admin/groups');
  const proposal = page.locator('.academic-material').filter({hasText:name});
  await proposal.getByRole('button',{name:'Review & approve'}).click();
  await dialog.getByLabel('Assign Dr. Meera Shah',{exact:true}).check();
  await dialog.getByRole('button',{name:'Approve and create group'}).click();
  await expect(dialog).toHaveCount(0);
  await expect(proposal).toContainText('approved');
  await login('faculty@demo.edu','Faculty123!');
  await page.goto('/faculty/groups');
  const group = page.locator('.group-card').filter({hasText:name});
  await group.getByRole('button',{name:'Manage',exact:true}).click();
  await dialog.getByRole('button',{name:'Create invitation & QR code'}).click();
  const link = await dialog.getByLabel('Invitation link',{exact:true}).getAttribute('value');
  expect(link).toContain('/join/');
  await expect(dialog.getByRole('img',{name:`Join request QR code for ${name}`})).toBeVisible();
  await login('asha@demo.edu','Student123!');
  await page.goto(link);
  await page.getByRole('button',{name:'Request to join group',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Your join request is awaiting approval.');
  await page.goto('/student/groups');
  const studentGroup = page.getByRole('article').filter({has:page.getByRole('heading',{name,exact:true})});
  await expect(studentGroup.getByRole('button',{name:'Awaiting approval',exact:true})).toBeDisabled();
  await expect(studentGroup.getByRole('button',{name:'Manage',exact:true})).toHaveCount(0);
  await login('faculty@demo.edu','Faculty123!');
  await page.goto('/faculty/groups');
  await group.getByRole('button',{name:'Manage',exact:true}).click();
  await dialog.getByRole('button',{name:'Approve Asha Rao',exact:true}).click();
  await expect(dialog.getByText('No pending join requests.',{exact:true})).toBeVisible();
  await login('asha@demo.edu','Student123!');
  await page.goto('/student/groups');
  await expect(studentGroup.getByRole('button',{name:`Leave ${name}`,exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.screenshot({path:testInfo.outputPath('approved-club-membership.png'),fullPage:true});
});
