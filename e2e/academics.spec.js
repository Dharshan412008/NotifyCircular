import { expect, test } from '@playwright/test';

test('assigns a class, shares subject material, and shows the matching student community', async ({ page }, testInfo) => {
  const login = async (email, password) => { await page.request.post('/api/auth/logout'); expect((await page.request.post('/api/auth/login', { data: { email, password } })).ok()).toBeTruthy(); };
  await login('faculty@demo.edu', 'Faculty123!');
  await page.request.put('/api/platform/profile', { data: { name: 'Dr. Meera Shah', department: 'IT', section: '', register_number: '', program: '', academic_year: '', bio: '' } });
  await login('admin@demo.edu', 'Admin123!');
  await page.request.post('/api/academics/classes', { data: { year: 2, department: 'ECE', section: 'A' } });
  await page.goto('/admin/groups');
  const otherDepartment = page.locator('form').filter({ has: page.getByRole('heading', { name: 'Year 2 · ECE · Section A', exact: true }) });
  await expect(otherDepartment.getByRole('checkbox', { name: /faculty@demo.edu/ })).toHaveCount(0);
  await expect(otherDepartment.getByText(/No staff from this department/)).toBeVisible();
  await page.getByLabel('Year', { exact: true }).selectOption('1');
  await page.getByLabel('Department', { exact: true }).fill('IT');
  await page.getByLabel('Section', { exact: true }).fill(testInfo.project.name === 'desktop-edge' ? 'A' : 'B');
  await page.getByRole('button', { name: 'Add class', exact: true }).click();
  const section = testInfo.project.name === 'desktop-edge' ? 'A' : 'B';
  const assignment = page.locator('form').filter({ has: page.getByRole('heading', { name: `Year 1 · IT · Section ${section}`, exact: true }) });
  await assignment.getByRole('checkbox', { name: /Dr\. Meera|faculty@demo.edu/ }).check();
  await assignment.getByRole('button', { name: 'Save assigned staff' }).click();
  await expect(assignment.getByText('Staff assignments saved.')).toBeVisible();
  await login('faculty@demo.edu', 'Faculty123!');
  await page.goto('/faculty/materials');
  await page.getByLabel('Class', { exact: true }).selectOption({ label: `Year 1 · IT · Section ${section}` });
  const subject = `Data Structures ${testInfo.project.name}`;
  await page.getByLabel('Subject name', { exact: true }).fill(subject);
  await page.getByRole('button', { name: 'Create subject', exact: true }).click();
  await page.getByLabel('Subject', { exact: true }).selectOption({ label: subject });
  await page.getByLabel('Material title').fill('Unit 1 notes');
  await page.getByLabel('File (up to 5 MB)').setInputFiles({ name: 'unit1.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\nUnit 1\n%%EOF') });
  await page.getByRole('button', { name: 'Upload material', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('Material shared with this class.');
  await expect(page.getByRole('link', { name: 'Download', exact: true })).toBeVisible();
  await login('asha@demo.edu', 'Student123!');
  await page.request.put('/api/platform/profile', { data: { name: 'Asha Rao', register_number: 'IT001', department: 'IT', section, program: 'BTech', academic_year: '2026-27', bio: '' } });
  await page.goto('/student/groups');
  await expect(page.getByText('Year → Department → Section')).toBeVisible();
  await page.getByRole('link', { name: `Section ${section} Subjects & materials` }).click();
  await expect(page.getByRole('heading', { name: subject, exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Upload material' })).toHaveCount(0);
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download', exact: true }).click();
  expect((await downloadPromise).suggestedFilename()).toBe('unit1.pdf');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.goto('/student/groups');
  await page.getByRole('link', { name: subject, exact: true }).click();
  await expect(page.getByRole('button', { name:'All subjects', exact:true })).toBeVisible();
  await expect(page.getByText('Unit 1 notes', { exact:true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('study-materials.png'), fullPage: true });
});
